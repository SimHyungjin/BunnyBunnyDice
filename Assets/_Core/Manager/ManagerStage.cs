/// <summary>
/// 매니저가 부팅의 어느 단계에서 초기화되는지 나타낸다.
///
/// 외부 SDK는 초기화되는 순간부터 기기 식별자를 수집하기 시작한다.
/// 그래서 SDK를 쓰는 매니저는 개인정보 동의를 받은 뒤에 초기화해야 하고,
/// 그 동의 화면을 띄우려면 UI·데이터 같은 매니저는 그보다 먼저 준비돼 있어야 한다.
/// 이 두 묶음을 가르는 것이 스테이지다.
/// </summary>
public enum ManagerStage
{
    /// <summary>외부 의존 없이 동작한다. 부팅 첫 단계에서 초기화된다. (오프라인에서도 안전)</summary>
    Core,

    /// <summary>외부 SDK에 의존한다. 동의 게이트를 통과한 뒤 초기화된다.</summary>
    Service,
}
